def _vt_workdir():
    """video-teardown's working-folder module, loaded by file (SI-56)."""
    m = sys.modules.get("vt_workdir")
    if m is None:
        import importlib.util
        spec = importlib.util.spec_from_file_location(
            "vt_workdir", Path(__file__).resolve().parents[2] / "tools" / "video-teardown" / "machine" / "workdir.py")
        m = importlib.util.module_from_spec(spec)
        sys.modules["vt_workdir"] = m
        spec.loader.exec_module(m)
    return m


def run_names():
    """Every teardown run's name, lowercased: filed (run-kit index) and live
    (runs/video-teardown/_work/), so an in-flight run still counts."""
    names = {r["label"].lower() for r in RKI.scan() if r["machine"] == "video-teardown"}
    live = _vt_workdir().root(WS)
    if live.is_dir():
        names |= {d.name.lower() for d in live.iterdir()}
    return names


def creator(handle, runs):
    d = REC / handle
    head = (d / "creator.md").read_text(encoding="utf-8", errors="replace") if (d / "creator.md").is_file() else ""
    def field(name):
        m = re.search(rf"\*\*{name}\*\*\s+(.+)", head)
        return m.group(1).strip() if m else ""
    followers = field("Followers")
    page = field("Page")
    title = (re.match(r"# (.+)", head) or [None, handle]).group(1)

    # posts: views from the record, shortcode from the Drive folder (NN-code)
    posts = []
    rows = re.findall(r"^\|\s*`[A-Z]+-(\d+)`\s*\|\s*([^|]+)\|\s*([\d,]+)\s*\|",
                      (d / "posts.md").read_text(encoding="utf-8", errors="replace")
                      if (d / "posts.md").is_file() else "", re.M)
    codes = {}
    pdir = DRIVE / handle / "posts"
    if pdir.is_dir():
        for f in pdir.iterdir():
            m = re.match(r"(\d+)-(\S+)", f.name)
            if m:
                codes[int(m.group(1))] = m.group(2)
    for nn, name, views in rows:
        nn = int(nn)
        code = codes.get(nn, "")
        torn = bool(code) and any(code.lower() in r for r in runs)
        posts.append(dict(nn=nn, name=name.strip(), views=int(views.replace(",", "")),
                          code=code, torn=torn))
    posts.sort(key=lambda p: -p["views"])
    queue = [p for p in posts if not p["torn"]][:QUEUE_TOP]
    return dict(handle=handle, title=title, followers=followers, page=page,
                posts=posts, held=len(posts),
                torn=sum(1 for p in posts if p["torn"]), queue=queue)


def saves_pool():
    try:
        rows = json.loads((HERE / "records" / "damon-saves" / "catalog.json")
                          .read_text(encoding="utf-8"))["rows"]
    except Exception:
        return {}
    import collections
    return dict(authors=len({r.get("author") for r in rows if r.get("author")}),
                posts=len(rows),
                buckets=dict(collections.Counter(r.get("bucket") or "?" for r in rows)))


def write_md(c):
    out = [f"# {c['handle']} — creator profile", "",
           f"Regenerated by `profile.py` — never hand-edited.",
           f"{c['title']} · {c['followers']} followers · {c['page']}", "",
           f"**{c['held']} posts held · {c['torn']} torn down**", "",
           "## Posts by views", "",
           "| # | post | views | torn down |", "|---|---|---|---|"]
    for p in c["posts"]:
        out.append(f"| {p['nn']:02d} | {p['name'][:44]} | {p['views']:,} | "
                   f"{'✓' if p['torn'] else '—'} |")
    out += ["", f"## Teardown queue — biggest untorn (top {QUEUE_TOP})", ""]
    for p in c["queue"]:
        out.append(f"- **{p['name'][:60]}** — {p['views']:,} views · post `{p['nn']:02d}-{p['code']}`")
    if not c["queue"]:
        out.append("- (everything big is torn down)")
    home = HERE / "creators" / c["handle"]
    home.mkdir(parents=True, exist_ok=True)
    (home / "PROFILE.md").write_text("\n".join(out) + "\n", encoding="utf-8")


