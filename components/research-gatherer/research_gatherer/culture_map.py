"""The culture map, built bottom-up from the evidence we hold.

    python3 components/research-gatherer/culture_map.py --brand B --avatar A [--dry-run] [--pack-only]
    python3 components/research-gatherer/culture_map.py --brand B --all [--dry-run]

the owner, 2026-10-06: "our systems need to be fully dynamic and based on the real
language only". A culture map used to be written by hand from the profile and
a hunch. This writes it from what people actually said and watched, and every
line has to show where it came from.

Three steps, one model call:

1. EVIDENCE PACK — deterministic, no model. For one avatar (and its subs):
   - bank rows tagged with a culture use (taste, cringe, subculture, in-word,
     community-voice, role-claimed, laugh) or trust-language, loudest first,
     read through the language layer's own engine. Id: the row id.
   - My Feeds: every feed that maps to this avatar or one of its subs (the
     feed -> avatar rule below). The top posts by latest views, the top
     authors and hashtags with post counts and summed views, the last sweep.
     Ids: `post:<url>`, `feed:<feed>@<author>`, `feed:<feed>#<hashtag>`.
   - culture digs: affinity.md and opportunity.md for each sub that has one.
     Id: `dig:<path under culture-digs/>`.
   - structured culture reads (`stages/1k-culture.json`, written by the video
     teardown) whose avatar is this one: every ref. Id: `run:<slug>#R2`.
   The profile and rules.md are NOT evidence. They only seed "To test".
2. WRITE — `prompts/culture-map-v1-damon.md`, one Claude call (the `claude`
   command, the same way annotate.py reads rows), every line ending in its
   evidence ids in brackets.
3. VERIFY — every line is parsed; a line that cites nothing, or cites an id
   that is not in the pack, is dropped and counted in the footer.

The first time it writes an avatar's map, the hand-built map is kept once as
`culture-map.hand-2026-10-06.md` (never overwritten). Its claims, and the
profile's and rules', go to the model as unbacked candidates: one moves into
the body only when pack evidence backs it; otherwise it is listed under To test.

Each real run leaves its pack, the prompt as sent, the raw answer and the
dropped lines at `runs/research/<brand>/culture-map-<avatar>-<stamp>/`.

Feed -> avatar (BOTTOMUP-SPEC): feed id `<brand>--<x>`. x is a core avatar id
in `core-avatars/avatars.json` -> that avatar; else the avatar whose
`sub_avatars` lists x -> that avatar, sub x. Feeds whose id starts with a skip
prefix in research.json (`skip_feed_prefixes`) and feeds that map to nothing
are skipped.
"""
