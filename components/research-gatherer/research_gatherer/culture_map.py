TRAIL = re.compile(r"\[([^\[\]]*)\]\s*$")
SEP_ROW = re.compile(r"^\|[\s:|-]+\|?$")


def cited_ids(line):
    """The ids a line cites: the bracket group(s) it ENDS with. For a table
    row, the bracket group(s) the last cell ends with."""
    s = line.strip()
    if s.startswith("|"):
        cells = [c.strip() for c in s.strip("|").split("|")]
        s = cells[-1] if cells else ""
    ids = []
    while True:
        m = TRAIL.search(s)
        if not m:
            break
        ids = [t.strip().strip("`").strip() for t in re.split(r"[,;]", m.group(1)) if t.strip()] + ids
        s = s[:m.start()].rstrip()
    return ids


def _section_of(heading):
    h = heading.lstrip("#").strip().lower()
    for s in SECTIONS:
        if h.startswith(s.lower()) or s.lower() in h:
            return s
    return heading.lstrip("#").strip()


def verify(body, known):
    """(kept text, report). Every line in a checked section must end with
    evidence ids that are all in `known`; a line that cites nothing or cites
    an unknown id is dropped. Headings, blank lines, table header/separator
    rows and the To test section pass unchecked."""
    lines = body.strip().splitlines()
    kept, dropped = [], []
    section, checked = None, 0
    for n, line in enumerate(lines):
        s = line.strip()
        if s.startswith("```"):
            continue
        if not s or s == "---":
            kept.append(line)
            continue
        if s.startswith("#"):
            section = _section_of(s) if s.startswith("##") and not s.startswith("###") else section
            kept.append(line)
            continue
        if section in UNCHECKED:
            kept.append(line)
            continue
        if s.startswith("|"):
            nxt = lines[n + 1].strip() if n + 1 < len(lines) else ""
            if SEP_ROW.match(s) or SEP_ROW.match(nxt):
                kept.append(line)
                continue
        ids = cited_ids(s)
        if not ids:
            dropped.append({"line": s, "section": section, "why": "cites nothing"})
            continue
        bad = [i for i in ids if i not in known]
        if bad:
            dropped.append({"line": s, "section": section, "why": "unknown id", "ids": bad})
            continue
        kept.append(line)
        checked += 1
    text = "\n".join(kept)
    return text, {"kept": checked, "dropped": dropped,
                  "uncited": sum(1 for d in dropped if d["why"] == "cites nothing"),
                  "unknown": sum(1 for d in dropped if d["why"] == "unknown id")}


def _empty_note(section):
    return "_Nothing waiting to be tested._" if section in UNCHECKED else "_Nothing in the evidence backs this section yet._"


def fill_empty_sections(text):
    """Every section heading present, and a section left with nothing says so."""
    out, lines = [], text.splitlines()
    present = {_section_of(l) for l in lines if l.strip().startswith("## ")}
    for i, l in enumerate(lines):
        out.append(l)
        if l.strip().startswith("## "):
            rest = lines[i + 1:]
            nxt = next((j for j, x in enumerate(rest) if x.strip().startswith("## ")), len(rest))
            if not any(x.strip() and not x.strip().startswith("#") for x in rest[:nxt]):
                out += ["", _empty_note(_section_of(l))]
    for s in SECTIONS:
        if s not in present:
            out += ["", f"## {s}", "", _empty_note(s)]
    return "\n".join(out)


