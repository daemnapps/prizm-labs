# ---------------------------------------------------------------- the roster and the feed rule

def roster(brand, ws=None):
    """{avatar id: [sub ids]} from core-avatars/avatars.json."""
    f = ws_root(ws) / "brands" / brand / "core-avatars" / "avatars.json"
    try:
        d = json.loads(f.read_text())
    except Exception:
        return {}
    av = d.get("avatars") if isinstance(d, dict) else d
    return {a["id"]: list(a.get("sub_avatars") or []) for a in av or [] if isinstance(a, dict) and a.get("id")}


def map_feed(feed_id, brands_roster):
    """(brand, avatar, sub) for a feed id, or None. `brands_roster` is
    {brand: roster(brand)}. The spec's rule, nothing more."""
    skip = tuple(engine._config().get("skip_feed_prefixes") or [])
    if "--" not in feed_id or feed_id.startswith(skip):
        return None
    brand, x = feed_id.split("--", 1)
    ros = brands_roster.get(brand) or {}
    if x in ros:
        return brand, x, None
    for a, subs in ros.items():
        if x in subs:
            return brand, a, x
    return None


def feeds_for(brand, avatar, ws=None):
    """[(feed id, sub or None, folder)] for this avatar, its own feed first."""
    root = Path(os.environ.get("VIEWER_FEEDS") or (ws_root(ws) / "components" / "swipe-organic" / "records" / "avatar-feeds"))
    ros = {brand: roster(brand, ws)}
    out = []
    for d in sorted(root.iterdir()) if root.is_dir() else []:
        if not d.is_dir():
            continue
        m = map_feed(d.name, ros)
        if m and m[1] == avatar:
            out.append((d.name, m[2], d))
    return sorted(out, key=lambda t: (t[1] is not None, t[0]))


