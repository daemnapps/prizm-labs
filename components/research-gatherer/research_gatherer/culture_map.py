def _language_engine(ws=None):
    p = next((q for q in (ws_root(ws) / "components" / "language-layer" / "language_layer" / "engine.py",
                          ws_root(ws) / "tools" / "language-layer" / "language_layer" / "engine.py") if q.is_file()),
             ws_root(ws) / "tools" / "language-layer" / "language_layer" / "engine.py")
    spec = importlib.util.spec_from_file_location("_cm_language_engine", p)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    mod.configure(workspace=ws_root(ws))
    return mod


def _likes(r):
    try:
        return int((r.get("signal") or {}).get("likes") or 0)
    except (TypeError, ValueError):
        return 0


def bank_evidence(brand, avatar, ws=None, L=None):
    """Culture-tagged rows for the avatar and its subs, loudest first. The
    engine filters (retired rows out, repeats collapsed); the order here is
    likes, because a map ranks by how loud a thing was, not a stage's tags."""
    L = L or _language_engine(ws)
    rows = L.load(brand, avatar, root=ws_root(ws))
    hits = L.query(rows, use=list(CULTURE_TAGS), limit=100000)
    hits = [r for r in hits if r.get("id")]
    hits.sort(key=lambda r: (-_likes(r), r.get("id")))
    keep = hits[:CAPS["rows"]]
    have = {r["id"] for r in keep}
    by_sub = defaultdict(list)
    for r in hits:
        if r.get("sub") and r["id"] not in have:
            by_sub[r["sub"]].append(r)
    for sub in sorted(by_sub):
        keep += by_sub[sub][:CAPS["rows_per_sub"]]
    items = []
    for r in keep:
        src = r.get("source") or {}
        items.append({"id": r["id"], "kind": "bank-row", "text": (r.get("text") or "")[:CAPS["text"]],
                      "use": [u for u in L._uses(r)], "likes": _likes(r), "repeats": r.get("_repeats", 1),
                      "sub": r.get("sub"), "source": src.get("name") or src.get("type"),
                      "pulled": src.get("pulled") or src.get("date")})
    fresh = max((i["pulled"] for i in items if i.get("pulled")), default=None)
    return items, {"rows_tagged": len(hits), "rows_in_pack": len(items), "newest_pulled": fresh}


# ---------------------------------------------------------------- evidence: My Feeds

def _jsonl(f):
    out = []
    try:
        for line in Path(f).read_text().splitlines():
            line = line.strip()
            if line:
                try:
                    out.append(json.loads(line))
                except Exception:
                    pass
    except Exception:
        pass
    return out


def latest_views(folder):
    """{item key: views} from the newest observation of each item."""
    best = {}
    for o in _jsonl(Path(folder) / "observations.jsonl"):
        k = o.get("item")
        if k and (k not in best or str(o.get("at") or "") >= str(best[k].get("at") or "")):
            best[k] = o
    return {k: int(v.get("views") or 0) for k, v in best.items()}


def feed_evidence(feed_id, sub, folder):
    try:
        items = json.loads((Path(folder) / "items.json").read_text()).get("items") or {}
    except Exception:
        items = {}
    views = latest_views(folder)
    posts = []
    for k, it in items.items():
        v = views.get(k, 0)
        posts.append((v, k, it))
    posts.sort(key=lambda t: (-t[0], t[1]))
    sweeps = _jsonl(Path(folder) / "sweeps.jsonl")
    last = max((s.get("at") or "" for s in sweeps), default="") or None
    out = []
    for v, k, it in posts[:CAPS["posts"]]:
        if not it.get("url"):
            continue
        sift = it.get("sift") or {}
        out.append({"id": f"post:{it['url']}", "kind": "feed-post", "feed": feed_id, "sub": sub,
                    "author": it.get("author"), "views": v,
                    "caption": re.sub(r"\s+", " ", it.get("caption") or "")[:CAPS["caption"]],
                    "hashtags": (it.get("hashtags") or [])[:8], "sift": sift.get("kind"),
                    "sift_keep": sift.get("keep"), "what": sift.get("what")})
    auth, tags = defaultdict(lambda: [0, 0]), defaultdict(lambda: [0, 0])
    for v, k, it in posts:
        if it.get("author"):
            auth[it["author"]][0] += 1
            auth[it["author"]][1] += v
        for h in {str(h).lower().lstrip("#") for h in it.get("hashtags") or []}:
            if h and h not in FILLER_TAGS:
                tags[h][0] += 1
                tags[h][1] += v
    rank = lambda d: sorted(d.items(), key=lambda kv: (-kv[1][1], kv[0]))
    for a, (n, s) in rank(auth)[:CAPS["authors"]]:
        out.append({"id": f"feed:{feed_id}@{a}", "kind": "feed-author", "feed": feed_id, "sub": sub,
                    "posts": n, "views": s})
    for h, (n, s) in [x for x in rank(tags) if x[1][0] >= 2][:CAPS["tags"]]:
        out.append({"id": f"feed:{feed_id}#{h}", "kind": "feed-hashtag", "feed": feed_id, "sub": sub,
                    "posts": n, "views": s})
    meta = {"feed": feed_id, "sub": sub, "posts": len(posts), "views": sum(p[0] for p in posts),
            "last_sweep": (last or "")[:10] or None}
    return out, meta


# ---------------------------------------------------------------- evidence: culture digs

def dig_evidence(brand, avatar, ws=None):
    root = ws_root(ws) / "components" / "swipe-organic" / "records" / "culture-digs"
    base = root / brand / avatar
    out, meta = [], []
    for d in sorted(x for x in base.iterdir() if x.is_dir()) if base.is_dir() else []:
        for name in ("affinity.md", "opportunity.md"):
            f = d / name
            if f.is_file():
                rel = f.relative_to(root).as_posix()
                when = _dt.date.fromtimestamp(f.stat().st_mtime).isoformat()
                out.append({"id": f"dig:{rel}", "kind": "dig", "sub": d.name,
                            "text": f.read_text()[:CAPS["dig_chars"]], "written": when})
                meta.append({"dig": rel, "written": when})
    return out, meta


# ---------------------------------------------------------------- evidence: structured culture reads

def kind_group(kind):
    """A read's `kind` is free text ("song, meme", "comment-room bit"); its
    first tag is the group."""
    return (re.split(r"[,;/|·(]", str(kind or ""))[0].strip().lower() or None)


RUN_ROOTS = (("runs", "video-teardown"), ("runs", "video-writing"))


def culture_reads(brand, avatar, ws=None):
    """Every stages/1k-culture.json whose avatar is this one. The same slug in
    two run trees keeps the newest parse."""
    found = {}
    for parts in RUN_ROOTS:
        root = ws_root(ws).joinpath(*parts)
        if not root.is_dir():
            continue
        for f in root.rglob("stages/1k-culture.json"):
            try:
                d = json.loads(f.read_text())
            except Exception:
                continue
            if d.get("avatar") != avatar or (d.get("brand") and d.get("brand") != brand):
                continue
            slug = d.get("run") or f.parent.parent.name
            if slug not in found or str(d.get("parsed_at") or "") > str(found[slug][0].get("parsed_at") or ""):
                found[slug] = (d, f)
    out, meta = [], []
    for slug in sorted(found):
        d, f = found[slug]
        for r in d.get("refs") or []:
            if not r.get("id"):
                continue
            out.append({"id": f"run:{slug}#{r['id']}", "kind": "culture-ref", "run": slug, "sub": d.get("sub"),
                        "post_url": d.get("post_url"), "culture_load": d.get("culture_load"),
                        "funny_or_straight": d.get("funny_or_straight"),
                        "ref_kind": r.get("kind"), "kind_group": kind_group(r.get("kind")),
                        "name_it_as": d.get("name_it_as") or [],
                        **{k: r.get(k) for k in ("name", "use", "who", "borrowed", "receipts",
                                                 "confidence", "recognizes", "why_lands")}})
        meta.append({"run": slug, "refs": len(d.get("refs") or []), "parsed_at": d.get("parsed_at")})
    return out, meta


# ---------------------------------------------------------------- the pack

def build_pack(brand, avatar, ws=None, L=None):
    items, sources, notes = [], {}, []
    rows, sources["bank"] = bank_evidence(brand, avatar, ws, L)
    items += rows
    sources["feeds"] = []
    for fid, sub, folder in feeds_for(brand, avatar, ws):
        got, meta = feed_evidence(fid, sub, folder)
        items += got
        sources["feeds"].append(meta)
    got, sources["digs"] = dig_evidence(brand, avatar, ws)
    items += got
    got, sources["reads"] = culture_reads(brand, avatar, ws)
    items += got
    if not sources["reads"]:
        notes.append("No structured culture reads (stages/1k-culture.json) for this avatar yet.")
    if not rows:
        notes.append("No culture-tagged bank rows for this avatar yet.")
    if not sources["feeds"]:
        notes.append("No My Feeds feed maps to this avatar or its subs.")
    seen, uniq = set(), []
    for i in items:                       # a post in two feeds is one piece of evidence
        if i["id"] not in seen:
            seen.add(i["id"])
            uniq.append(i)
    return {"brand": brand, "avatar": avatar, "subs": roster(brand, ws).get(avatar, []),
            "built_at": _dt.datetime.now().astimezone().isoformat(timespec="minutes"),
            "items": uniq, "sources": sources, "notes": notes}


def pack_ids(pack):
    return {i["id"] for i in pack["items"]}


def pack_counts(pack):
    c = defaultdict(int)
    for i in pack["items"]:
        c[i["kind"]] += 1
    return dict(c)


def render_pack(pack):
    """The pack as the model (and a dry run) sees it: one evidence item per line."""
    out = []
    for n in pack["notes"]:
        out.append(f"NOTE: {n}")
    groups = (("BANK ROWS (real words, loudest first)", "bank-row"), ("FEED POSTS (top by latest views)", "feed-post"),
              ("FEED AUTHORS (posts · summed views)", "feed-author"), ("FEED HASHTAGS (posts · summed views)", "feed-hashtag"),
              ("CULTURE DIGS", "dig"), ("CULTURE READS FROM TEARDOWNS", "culture-ref"))
    for title, kind in groups:
        its = [i for i in pack["items"] if i["kind"] == kind]
        out.append(f"\n## {title} — {len(its)}")
        if not its:
            out.append("(none)")
        for i in its:
            sub = f" sub={i['sub']}" if i.get("sub") else ""
            if kind == "bank-row":
                out.append(f"[{i['id']}]{sub} likes={i['likes']} said={i['repeats']}x use={','.join(i['use'])} "
                           f"src={i.get('source')} :: {json.dumps(i['text'], ensure_ascii=False)}")
            elif kind == "feed-post":
                out.append(f"[{i['id']}] feed={i['feed']}{sub} views={i['views']:,} @{i['author']} "
                           f"kind={i.get('sift')}{' (sift: junk)' if i.get('sift_keep') is False else ''} "
                           f"tags={','.join(i['hashtags'])} :: {json.dumps(i['caption'], ensure_ascii=False)}")
            elif kind in ("feed-author", "feed-hashtag"):
                out.append(f"[{i['id']}]{sub} posts={i['posts']} views={i['views']:,}")
            elif kind == "dig":
                body = "\n".join("    | " + l for l in i["text"].splitlines())
                out.append(f"[{i['id']}]{sub} written {i['written']}:\n{body}\n[end {i['id']}]")
            else:
                out.append(f"[{i['id']}]{sub} {i.get('name')} · kind={i.get('kind_group')} ({i.get('ref_kind')}) load={i.get('culture_load')} use={i.get('use')} "
                           f"confidence={i.get('confidence')} who={i.get('who')} borrowed={i.get('borrowed')} "
                           f"receipts={json.dumps(i.get('receipts'), ensure_ascii=False)} "
                           f"recognizes={i.get('recognizes')} why={i.get('why_lands')}")
    return "\n".join(out)


# ---------------------------------------------------------------- the hand-built map and the candidates

def preserve_hand(brand, avatar, ws=None):
    """Keep the hand-built map once, before the first generated write. Never
    overwrites the copy; never copies a map this tool wrote."""
    home = avatar_home(brand, avatar, ws)
    cur, hand = home / MAP_NAME, home / HAND_NAME
    if hand.exists():
        return hand
    if cur.is_file() and MARK not in cur.read_text():
        shutil.copy2(cur, hand)
        return hand
    return None


def candidate_text(brand, avatar, ws=None):
    """The unbacked candidates: the hand-built map (the kept copy, else the
    current map when it is still hand-built), the profile, the rules."""
    home = avatar_home(brand, avatar, ws)
    parts = []
    hand = home / HAND_NAME
    cur = home / MAP_NAME
    src = hand if hand.is_file() else (cur if cur.is_file() and MARK not in cur.read_text() else None)
    for label, f in (("THE HAND-BUILT MAP", src), ("THE PROFILE", home / "profile.md"),
                     ("THE VOICE RULES", home / "language" / "rules.md")):
        if f is not None and f.is_file():
            parts.append(f"=== {label} ({f.relative_to(ws_root(ws)).as_posix()}) ===\n{f.read_text()}")
    return "\n\n".join(parts) or "(none on file)"


# ---------------------------------------------------------------- write

def fill_prompt(pack, candidates, label=None):
    tmpl = PROMPT.read_text().split("\n---\n", 1)[-1]
    subs = ", ".join(pack["subs"]) or "(none)"
    return (tmpl.replace("{{BRAND}}", label or pack["brand"]).replace("{{AVATAR}}", pack["avatar"])
            .replace("{{SUBS}}", subs).replace("{{PACK}}", render_pack(pack))
            .replace("{{CANDIDATES}}", candidates))


def model_name(override=None):
    return override or (engine.CFG.get("ownvoice") or {}).get("model") or "claude-sonnet-5"


def call_model(prompt, model, claude=None):
    claude = claude or shutil.which("claude")
    if not claude:
        raise RuntimeError("no `claude` command on this machine")
    p = subprocess.run([claude, "-p", "--output-format", "text", "--model", model],
                       input=prompt, capture_output=True, text=True, timeout=1800)
    if p.returncode != 0 or not p.stdout.strip():
        raise RuntimeError(f"model call failed: {(p.stderr or p.stdout)[:300]}")
    return p.stdout


