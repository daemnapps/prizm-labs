#!/usr/bin/env python3
"""One registered video brief with distinct, accepted writing variants. Generates no media."""
import argparse
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import stage_handoff as SH


def safe(value):
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]*', str(value)):
        raise ValueError('Invalid variant or run identifier: %s' % value)
    return str(value)


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def variants_of(record):
    rows = record.get('variants') or []
    if len(rows) != 3 or len({safe(x['id']) for x in rows}) != 3:
        raise ValueError('A grouped brief requires three distinct variation IDs')
    if len({safe(x['source_run']) for x in rows}) != 3:
        raise ValueError('Each variation must retain a distinct source run')
    return rows


def build(spec, key, root=None, source_root=None, drive=True):
    root = Path(root or SH.repo()).resolve()
    source_root = Path(source_root or root).resolve()
    rows = variants_of(spec)
    brand, product = safe(spec['brand']), safe(spec['product'])
    register = (SH._json(root / 'components/image-teardown/briefs.json') or {}).get('briefs') or {}
    row = register.get(key) or {}
    if row.get('brand') != brand or row.get('product') != product or row.get('type') != 'video-ai':
        raise ValueError('The grouped brief must have its own matching video-ai register entry')
    sys.path.insert(0, str(root / 'components/video-writing/machine'))
    from writing_result import inspect_result
    forms = {x['id'] for x in (SH._json(root / 'components/video-production/formats/bank.json') or {}).get('formats', [])
             if x.get('status') != 'deprecated'}
    prepared = []
    for variant in rows:
        src = source_root / 'runs/video-teardown/_work' / safe(variant['source_run'])
        rj = SH._json(src / 'run.json') or {}
        result = inspect_result(src)
        if not result.get('accepted'):
            raise ValueError('%s writing is not accepted: %s' % (src.name, result.get('blockers')))
        if rj.get('brand') != brand or rj.get('product') != product or rj.get('production_route') != 'ai':
            raise ValueError('%s has a different brand, product or route' % src.name)
        form = rj.get('format_id')
        if form not in forms:
            raise ValueError('%s needs a banked production format' % src.name)
        audience = (rj.get('declared_audience') or {}).get('avatar') or (rj.get('audience') or {}).get('_avatar')
        if audience != spec['avatar']:
            raise ValueError('%s audience %s differs from grouped brief %s' % (src.name, audience, spec['avatar']))
        prepared.append((variant, src, rj, result, form))
    out = SH.folder('video-producer', brand, key, root)
    out.mkdir(parents=True, exist_ok=True)
    (out / 'returned').mkdir(exist_ok=True)
    manifest_rows, body, runlines = [], ['# ' + spec['title'], '', 'Three distinct selected control variations of one brief. Read and produce each variation separately; never run this combined review document as one production script. Optional opening alternatives retained inside source briefs are reference material, not additional assignments.', ''], ['# Production actions', '', 'Make exactly one control cut for each of the three selected variations. Optional source opening alternatives are not extra queue jobs. Writing is checked; no voice, pictures, clips or finished cut has been generated by this handoff. Preview each variation with its exact command below. Production spend requires the existing production workflow approval.', '']
    import pack
    for variant, src, rj, result, form in prepared:
        vid = safe(variant['id']); folder = out / 'variants' / vid
        folder.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src / result['source']['path'], folder / 'BRIEF.md')
        (folder / 'writing').mkdir(exist_ok=True)
        (folder / 'writing/result.json').write_text(json.dumps(result, indent=2) + '\n')
        shutil.copy2(src / 'run.json', folder / 'writing/source-run.json')
        # Keep the current writing evidence portable without copying inherited media again.
        for directory in ('stages', 'prompts', 'qc-log'):
            for original in sorted((src / directory).rglob('*')):
                if original.is_file() and original.suffix in ('.md', '.json', '.txt', '.jsonl'):
                    target = folder / 'writing' / original.relative_to(src)
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(original, target)
        for receipt in sorted((src / 'revalidation').glob('*/result.json')):
            target = folder / 'writing' / receipt.relative_to(src)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(receipt, target)
        evidence_names = ['RULINGS.md', 'story.md', 'owner-script.md', 'owner-controls.json',
                          'language-exposure.json', 'verbatim-sources.md', 'execution-decisions.md', 'stages/4f-audit.md']
        for pattern in ('claim-execution*.md', 'factual-copy-execution*.md', 'casting-continuity*.md', 'casting-continuity*.sources.json'):
            evidence_names.extend(p.name for p in src.glob(pattern) if p.is_file())
        source_evidence = {}
        for name in sorted(set(evidence_names)):
            original = src / name
            if original.is_file():
                if src.resolve() not in original.resolve().parents:
                    raise ValueError('Source evidence must stay inside its run: %s' % name)
                target = folder / 'writing' / Path(name).name
                shutil.copy2(original, target)
                source_evidence[target.name] = digest(target)
        (folder / 'teardown').mkdir(exist_ok=True)
        for original, dest in pack.TEARDOWN:
            if (src / original).is_file():shutil.copy2(src / original, folder / 'teardown' / dest)
        (folder / 'refs').mkdir(exist_ok=True)
        for original, dest in (('source.mp4', 'swipe.mp4'), ('poster.jpg', 'swipe-poster.jpg')):
            if not (src / original).is_file():raise ValueError('%s lacks %s' % (src.name, original))
            shutil.copy2(src / original, folder / 'refs' / dest)
        rel = folder.relative_to(root).as_posix()
        label = key + '-' + vid.lower()
        command = 'python3 components/video-production/machine/run.py start %s/BRIEF.md --brand %s --format %s --label %s --dry-run' % (rel, brand, form, label)
        info = dict(variant, folder='variants/' + vid, format=form, production_label=label,
                    brief_sha256=digest(folder / 'BRIEF.md'), source_evidence_sha256=source_evidence, writing_accepted=True, run=command)
        manifest_rows.append(info)
        (folder / 'SWIPE.md').write_text('# Source swipe\n\nSource run: `%s`. Original footage: `refs/swipe.mp4`; poster: `refs/swipe-poster.jpg`. Full source continuation packet: %s\n' % (src.name, variant.get('source_url') or 'see parent manifest'))
        body += ['## ' + vid + ' · ' + variant['title'], '', 'Source: `' + src.name + '` · production profile: `' + form + '`', '', (folder / 'BRIEF.md').read_text(), '']
        runlines += ['## ' + vid + ' · ' + variant['title'], '', '    ' + command, '', 'Return this variation as `' + label + '-control.mp4` plus its own `' + label + '-control-cover.png` and cover provenance record. Retain its unique ID in production and edit records.', '']
    (out / 'BRIEF.md').write_text('\n'.join(body))
    (out / 'RUN.md').write_text('\n'.join(runlines))
    sys.path.append(str(root / 'components/briefs'))
    import video_delivery
    video_delivery.pack(out)  # combined review brief only; accepted variation bytes remain exact
    rel = out.relative_to(root).as_posix()
    say = 'Open %s. Read START.md and the three separate full briefs under variants/. Preview each production action in RUN.md; keep their variation IDs.' % key
    man = {'schema': SH.SCHEMA, 'status': 'draft', 'state': 'open', 'chain': 'video', 'stage': 'video-production',
           'role': 'video-producer', 'work_role': 'video-producer', 'packet_kind': 'grouped-video-brief', 'brand': brand,
           'product': product, 'avatar': spec['avatar'], 'key': key, 'brief': 'brief-' + SH.number(key), 'title': spec['title'],
           'route': 'ai', 'format': 'per-variant', 'writing_accepted': True, 'production_ready': True, 'media_generated': False,
           'variants': manifest_rows, 'holders': SH.holders('video-producer'),
           'activate': {'skill': 'video-production', 'say': say, 'run': 'python3 components/video-edit/handoff/group.py plan ' + rel},
           'sources': [{'path': 'runs/video-teardown/_work/' + v['source_run'], 'what': v['id'] + ' accepted writing'} for v in rows],
           'completion': {'policy': 'new-workflow-design/builds/pm-tool/session-handoff.md', 'owner': 'Assigned staff member in their own account', 'reviewer': spec.get('reviewer', 'assigned final reviewer'), 'done': 'All three variations completed through authorized production and editing, checks and fixes passed, outputs filed, and finished work returned to the assigned final reviewer.'},
           'next': {'stage': 'video-edit', 'role': 'video-editor', 'how': 'One edit kit per distinct variation; keep the parent brief key and variation ID.'}}
    (out / 'run.json').write_text(json.dumps({'schema': 'grouped-video-brief/v1', 'key': key, 'brand': brand, 'product': product, 'variants': manifest_rows, 'media_generated': False}, indent=2) + '\n')
    (out / 'START.md').write_text('# ' + spec['title'] + '\n\n' + say + '\n\nFinal reviewer: ' + spec.get('reviewer', 'assigned final reviewer') + '.\n\nThis is one job with three separate variations. Writing has passed its checks. The producer continues with production previews, approved generation and the cut. No generated media or finished cuts are claimed.\n\n' + '\n'.join('- **%s**: %s — `variants/%s/BRIEF.md`' % (v['id'], v['title'], v['id']) for v in manifest_rows) + '\n\nThe assigned staff member owns all three variations through completion in their own account: follow the existing authorized production workflow and budget, run checks, resolve routine failures, file the outputs, and return finished work to the assigned final reviewer. Carry routine execution through without bouncing routine steps back to the reviewer. Follow `new-workflow-design/builds/pm-tool/session-handoff.md`; existing review and launch boundaries still apply.\n\nUse RUN.md for exact next actions. Earlier single-run packets are retained as source history and point here; they are not additional assignments.\n')
    man['files'] = sorted(set(SH.files(out)) | {'HANDOFF.json'})
    (out / 'HANDOFF.json').write_text(json.dumps(man, indent=2) + '\n')
    if drive:SH.mirror(out, root)
    return out, man


def checks(folder, manifest):
    out = []
    try:rows = variants_of(manifest)
    except (KeyError, ValueError) as exc:return [{'group': 'Variations', 'check': 'Three distinct source variations', 'ok': False, 'evidence': str(exc)}]
    for v in rows:
        base = Path(folder) / 'variants' / safe(v['id'])
        result = SH._json(base / 'writing/result.json') or {}
        brief = base / 'BRIEF.md'
        ok = brief.is_file() and digest(brief) == v.get('brief_sha256') == (result.get('source') or {}).get('sha256')
        evidence_ok = all(Path(name).name == name and (base / 'writing' / name).is_file()
                          and digest(base / 'writing' / name) == value
                          for name, value in (v.get('source_evidence_sha256') or {}).items())
        out.append({'group': 'Variations', 'check': v['id'] + ' current accepted brief and source evidence bytes', 'ok': bool(ok and evidence_ok and result.get('accepted') and v.get('writing_accepted')), 'evidence': v['source_run']})
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest='cmd', required=True)
    b = sub.add_parser('build');b.add_argument('spec');b.add_argument('--key', required=True);b.add_argument('--source-root');b.add_argument('--no-drive', action='store_true')
    p = sub.add_parser('plan');p.add_argument('folder')
    a = ap.parse_args()
    if a.cmd == 'build':
        out, _ = build(SH._json(Path(a.spec)), a.key, source_root=a.source_root, drive=not a.no_drive);print(out)
    else:
        f = Path(a.folder);m = SH.manifest(f) or {};result = checks(f, m)
        if not result or not all(x['ok'] for x in result):raise SystemExit(json.dumps(result, indent=2))
        print(json.dumps({'key': m['key'], 'variations': [{'id': v['id'], 'run': v['run']} for v in m['variants']]}, indent=2))


if __name__ == '__main__':main()
