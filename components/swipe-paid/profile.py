def main():
    markets = {}
    try:
        src = json.loads(SOURCES.read_text(encoding="utf-8"))["sources"]
        markets = {k: v.get("market", "") for k, v in src.items()}
    except Exception:
        pass
    ids, slugs = torn_down()
    profiles = []
    for d in brands():
        pr = profile(d, markets, ids, slugs)
        write_md(pr)
        profiles.append(pr)
        print(f"  {pr['brand']:16} {pr['angles']:3} angles · queue {len(pr['queue'])}")
    write_html(profiles)
    print(f"-> swipe-intelligence.html · {sum(len(p['queue']) for p in profiles)} teardown candidates")


if __name__ == "__main__":
    main()
