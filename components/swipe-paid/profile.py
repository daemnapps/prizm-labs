sys.path.append(str(HERE.parent / "run-kit"))     # appended, never ahead of this tool
from run_kit.paths import repo  # noqa: E402  the one workspace locator (triage page 12)
WS = repo(HERE)
from run_kit import index as RKI  # noqa: E402  the filed teardown shelf (SI-56)


def _vt_workdir():
    """video-teardown's working-folder module, loaded by file (SI-56)."""
    m = sys.modules.get("vt_workdir")
    if m is None:
        import importlib.util
        spec = importlib.util.spec_from_file_location(
            "vt_workdir", Path(__file__).resolve().parents[2] / "tools" / "video-teardown" / "machine" / "workdir.py")
        m = importlib.util.module_from_spec(spec)
        sys.modules["vt_workdir"] = m
        spec.loader.exec_module(m)
    return m


SOURCES = WS / "tools" / "copywriter" / "library" / "sources.json"

QUEUE_MIN_CREATIVES = 8      # an angle this hot with no teardown is a gap


def esc(s):
    return html.escape(str(s))


def brands():
    for d in sorted(HERE.iterdir()):
        if (d / "blocks.json").is_file():
            yield d


def torn_down():
    """Which swipe material already has a teardown run, by ad id and slug —
    filed (run-kit index) and live (runs/video-teardown/_work/)."""
    names = {r["label"].lower() for r in RKI.scan() if r["machine"] == "video-teardown"}
    live = _vt_workdir().root(WS)
    if live.is_dir():
        names |= {d.name.lower() for d in live.iterdir()}
    ids, slugs = set(), set()
    for name in sorted(names):
        slugs.add(name)
        m = re.findall(r"(\d{9,})", name)
        ids.update(m)
    return ids, slugs


def profile(d, markets, ids, slugs):
    data = json.loads((d / "blocks.json").read_text(encoding="utf-8"))
    blocks = sorted(data.get("blocks", []),
                    key=lambda b: (b.get("count", 0), b.get("max_variants", 0)),
                    reverse=True)
    total = sum(b.get("count", 0) for b in blocks) or 1
    video = data.get("video", 0); image = data.get("image", 0)
    seasonal = sum(1 for b in blocks if b.get("seasonal"))
    top3 = sum(b.get("count", 0) for b in blocks[:3])
    pages = {}
    for b in blocks:
        lp = b.get("landing_page") or "(unresolved)"
        pages[lp] = pages.get(lp, 0) + b.get("count", 0)
    pages = sorted(pages.items(), key=lambda kv: -kv[1])

    queue = []
    for b in blocks:
        if b.get("count", 0) < QUEUE_MIN_CREATIVES:
            break
        done = any(str(i) in ids for i in (b.get("ad_ids") or [])) or \
               any(b.get("slug", "§") in s for s in slugs)
        if not done:
            queue.append(b)

    return dict(
        brand=d.name, market=markets.get(d.name, "(market unruled)"),
        creatives=data.get("creatives", total), angles=len(blocks),
        video=video, image=image, seasonal=seasonal,
        concentration=round(top3 / total * 100),
        blocks=blocks, pages=pages[:5], queue=queue)


def write_md(p):
    out = [f"# {p['brand']} — swipe profile",
           "",
           f"Regenerated by `profile.py` — never hand-edited. Market: {p['market']}",
           "",
           "## The strategy, as the numbers show it",
           "",
           f"- **{p['creatives']} creatives** across **{p['angles']} angles** in the window",
           f"- Format lean: **{p['video']} video / {p['image']} image**",
           f"- Top 3 angles carry **{p['concentration']}%** of all creatives"
           + " — concentrated bet" if p['concentration'] >= 50 else
           f"- Top 3 angles carry **{p['concentration']}%** of all creatives — wide testing",
           f"- {p['seasonal']} angles flagged seasonal",
           "",
           "## Where the traffic goes",
           ""]
    for lp, c in p["pages"]:
        out.append(f"- {lp} — {c} creatives")
    out += ["", "## Angle leaderboard (top 10 by live creatives)", "",
            "| # | angle | live | max variants | page |", "|---|---|---|---|---|"]
    for i, b in enumerate(p["blocks"][:10], 1):
        out.append(f"| {i} | {b.get('headline','')[:60]} | {b.get('count',0)} "
                   f"| {b.get('max_variants',0)} | {(b.get('landing_page') or '')[:40]} |")
    out += ["", f"## Teardown queue — scaling (≥{QUEUE_MIN_CREATIVES} live), no teardown yet", ""]
    if p["queue"]:
        for b in p["queue"]:
            out.append(f"- **{b.get('headline','')[:70]}** — {b.get('count')} live, "
                       f"{b.get('max_variants')} variants · rep ad `{b.get('rep_ad_id')}`")
    else:
        out.append("- (none — everything hot is torn down, or nothing clears the bar)")
    (HERE / p["brand"] / "PROFILE.md").write_text("\n".join(out) + "\n", encoding="utf-8")


