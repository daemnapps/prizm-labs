#!/usr/bin/env python3
"""The living profile of every brand we swipe.

    python3 profile.py

One profile per swiped brand — their strategy as the numbers show it, their
angles ranked by heat, their formats, their pages, and the TEARDOWN QUEUE:
what is scaling for them that we have not torn down yet. Regenerated from the
sweep data on every run, so it stays true as new sweeps land; nothing here is
hand-kept.

Writes <brand>/PROFILE.md per brand and one swipe-intelligence.html across
all of them. The signal definitions come from METHOD.md — count is live
creatives in the window, max_variants is cloning heat ("nobody clones a
loser"), and none of it is spend data, so the queue is an inference we can
name, never a result.
"""
